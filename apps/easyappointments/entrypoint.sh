#!/bin/sh
# Container entrypoint: write config.php and application/config/email.php
# from the same environment variables the official alextselegidis/easyappointments
# image reads, wait for the database, then run ePHPm in the foreground.
set -eu

HTML=/var/www/html
CONFIG="${EPHPM_CONFIG:-/etc/ephpm/ephpm.toml}"

# storage/ lives in a volume; seed it when it was created empty.
if [ -z "$(ls -A "$HTML/storage" 2>/dev/null)" ]; then
    cp -a /usr/local/share/easyappointments/storage/. "$HTML/storage/"
fi
mkdir -p "$HTML/storage/backups" "$HTML/storage/cache" "$HTML/storage/logs" \
         "$HTML/storage/sessions" "$HTML/storage/uploads"

BASE_URL="${BASE_URL:-http://localhost:8080}"
DB_HOST="${DB_HOST:-127.0.0.1}"
DB_NAME="${DB_NAME:-easyappointments}"
DB_USERNAME="${DB_USERNAME:-root}"
DB_PASSWORD="${DB_PASSWORD:-}"

# Values land inside single-quoted PHP strings; escape what would end them.
q() { printf '%s' "$1" | sed "s/\\\\/\\\\\\\\/g; s/'/\\\\'/g"; }
# TRUE/FALSE flags, as the official image spells them.
b() { case "$(printf '%s' "$1" | tr '[:upper:]' '[:lower:]')" in true|1|yes) printf 'true' ;; *) printf 'false' ;; esac; }

cat > "$HTML/config.php" <<EOF
<?php
// Generated by entrypoint.sh on every start — change the container
// environment, not this file.
class Config
{
    const BASE_URL = '$(q "$BASE_URL")';
    const LANGUAGE = '$(q "${LANGUAGE:-english}")';
    const DEBUG_MODE = $(b "${DEBUG_MODE:-FALSE}");

    const DB_HOST = '$(q "$DB_HOST")';
    const DB_NAME = '$(q "$DB_NAME")';
    const DB_USERNAME = '$(q "$DB_USERNAME")';
    const DB_PASSWORD = '$(q "$DB_PASSWORD")';

    const GOOGLE_SYNC_FEATURE = $(b "${GOOGLE_SYNC_FEATURE:-FALSE}");
    const GOOGLE_CLIENT_ID = '$(q "${GOOGLE_CLIENT_ID:-}")';
    const GOOGLE_CLIENT_SECRET = '$(q "${GOOGLE_CLIENT_SECRET:-}")';
}
EOF

cat > "$HTML/application/config/email.php" <<EOF
<?php defined('BASEPATH') or exit('No direct script access allowed');
// Generated by entrypoint.sh from the MAIL_* environment variables.
// @link https://codeigniter.com/userguide3/libraries/email.html
\$config['useragent'] = 'Easy!Appointments';
\$config['protocol'] = '$(q "${MAIL_PROTOCOL:-mail}")';
\$config['mailtype'] = 'html';
\$config['smtp_debug'] = '$(q "${MAIL_SMTP_DEBUG:-0}")';
\$config['smtp_auth'] = $(b "${MAIL_SMTP_AUTH:-0}");
\$config['smtp_host'] = '$(q "${MAIL_SMTP_HOST:-}")';
\$config['smtp_user'] = '$(q "${MAIL_SMTP_USER:-}")';
\$config['smtp_pass'] = '$(q "${MAIL_SMTP_PASS:-}")';
\$config['smtp_crypto'] = '$(q "${MAIL_SMTP_CRYPTO:-tls}")';
\$config['smtp_port'] = $(printf '%d' "${MAIL_SMTP_PORT:-587}");
\$config['from_name'] = '$(q "${MAIL_FROM_NAME:-}")';
\$config['from_address'] = '$(q "${MAIL_FROM_ADDRESS:-}")';
\$config['reply_to'] = '$(q "${MAIL_REPLY_TO_ADDRESS:-}")';
\$config['crlf'] = "\r\n";
\$config['newline'] = "\r\n";
EOF

# The official image pins base_url to BASE_URL (the app otherwise derives it
# from each request). Same here, appended once to the framework config.
CI_CONFIG="$HTML/application/config/config.php"
LINE="\$config['base_url'] = '$(q "$BASE_URL")';"
if ! grep -qF -- "$LINE" "$CI_CONFIG"; then
    sed -i "/^\$config\['base_url'\] = '.*'; # ephpm-recipe$/d" "$CI_CONFIG"
    printf '%s # ephpm-recipe\n' "$LINE" >> "$CI_CONFIG"
fi

# Wait for an external database (the embedded one starts with the server).
case "$DB_HOST" in
    127.0.0.1|localhost) ;;
    *)
        echo "==> waiting for database at $DB_HOST"
        i=0
        until ephpm php -r '
            mysqli_report(MYSQLI_REPORT_OFF);
            exit(@mysqli_connect($argv[1], $argv[2], $argv[3], $argv[4]) ? 0 : 1);
        ' "$DB_HOST" "$DB_USERNAME" "$DB_PASSWORD" "$DB_NAME" 2>/dev/null; do
            i=$((i + 1))
            [ "$i" -ge 60 ] && { echo "!!! database at $DB_HOST not reachable after 60 tries" >&2; exit 1; }
            sleep 2
        done
        ;;
esac

# The schema is created by the web installer (/index.php/installation) on
# first visit, exactly as with the official image.
exec ephpm serve --config "$CONFIG" "$@"
