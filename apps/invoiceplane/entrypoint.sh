#!/bin/sh
# Container entrypoint: generate ipconfig.php from the environment (the same
# variables the official image's entrypoint reads), migrate, create the
# default admin, then run ePHPm in the foreground.
set -eu

HTML=/var/www/html
CONFIG="${EPHPM_CONFIG:-/etc/ephpm/ephpm.toml}"
IPCONFIG="$HTML/ipconfig.php"

# uploads/ and storage/ live in volumes; seed them when they were created empty.
for d in uploads storage; do
    if [ -z "$(ls -A "$HTML/$d" 2>/dev/null)" ]; then
        cp -a "/usr/local/share/invoiceplane/$d/." "$HTML/$d/"
    fi
done
mkdir -p "$HTML/application/logs" "$HTML/storage/temp" "$HTML/uploads/temp/mpdf"

# A config value with a newline could inject extra lines (e.g. DISABLE_SETUP=false).
NL='
'
for v in IP_URL DB_HOSTNAME DB_USERNAME DB_PASSWORD DB_DATABASE DB_PORT ENCRYPTION_KEY \
         CI_ENV ENABLE_DEBUG SESS_SAVE_PATH CUSTOM_TEMPLATES_FOLDER SUMEX_URL DEFAULT_LANGUAGE; do
    eval "x=\${$v:-}"
    case "$x" in
        *"$NL"*) echo "!!! $v must not contain newlines" >&2; exit 1 ;;
    esac
done
val() { printf '%s' "$1"; }

# The encryption key must be stable: it protects stored settings. Use
# ENCRYPTION_KEY from the environment, else generate one once and keep it in
# the storage volume (the official image requires the variable instead).
if [ -z "${ENCRYPTION_KEY:-}" ]; then
    KEYFILE="$HTML/storage/ephpm-encryption-key"
    if [ ! -f "$KEYFILE" ]; then
        ephpm php -r 'echo "base64:" . base64_encode(random_bytes(32));' > "$KEYFILE"
        chmod 600 "$KEYFILE"
    fi
    ENCRYPTION_KEY="$(cat "$KEYFILE")"
fi

DB_HOSTNAME="${DB_HOSTNAME:-db}"
DB_PORT="${DB_PORT:-3306}"
DB_USERNAME="${DB_USERNAME:-invoiceplane}"
DB_PASSWORD="${DB_PASSWORD:-invoiceplane}"
DB_DATABASE="${DB_DATABASE:-invoiceplane}"

cat > "$IPCONFIG" <<EOF
# <?php exit('No direct script access allowed'); ?>
# InvoicePlane configuration — generated by entrypoint.sh on every start.
# Change values through the container environment, not here.

IP_URL=$(val "${IP_URL:-http://localhost:8080}")

ENABLE_DEBUG=$(val "${ENABLE_DEBUG:-false}")
CI_ENV=$(val "${CI_ENV:-production}")

X_FRAME_OPTIONS=$(val "${X_FRAME_OPTIONS:-SAMEORIGIN}")
ENABLE_X_CONTENT_TYPE_OPTIONS=$(val "${ENABLE_X_CONTENT_TYPE_OPTIONS:-true}")
COOKIE_SECURE=$(val "${COOKIE_SECURE:-false}")
SESS_SAVE_PATH=$(val "${SESS_SAVE_PATH:-$HTML/storage/framework/sessions}")
SESS_EXPIRATION=$(val "${SESS_EXPIRATION:-864000}")
SESS_MATCH_IP=$(val "${SESS_MATCH_IP:-true}")
SESS_REGENERATE_DESTROY=$(val "${SESS_REGENERATE_DESTROY:-true}")

DEFAULT_LANGUAGE=$(val "${DEFAULT_LANGUAGE:-english}")

DISABLE_SETUP=true
REMOVE_INDEXPHP=true

DB_HOSTNAME=$(val "$DB_HOSTNAME")
DB_USERNAME=$(val "$DB_USERNAME")
DB_PASSWORD=$(val "$DB_PASSWORD")
DB_DATABASE=$(val "$DB_DATABASE")
DB_PORT=$(val "$DB_PORT")

CUSTOM_TEMPLATES_FOLDER=$(val "${CUSTOM_TEMPLATES_FOLDER:-}")
CUSTOM_INVOICE_TEMPLATES_PDF=$(val "${CUSTOM_INVOICE_TEMPLATES_PDF:-}")
CUSTOM_INVOICE_TEMPLATES_PUBLIC=$(val "${CUSTOM_INVOICE_TEMPLATES_PUBLIC:-}")
CUSTOM_QUOTE_TEMPLATES_PDF=$(val "${CUSTOM_QUOTE_TEMPLATES_PDF:-}")
CUSTOM_QUOTE_TEMPLATES_PUBLIC=$(val "${CUSTOM_QUOTE_TEMPLATES_PUBLIC:-}")

LEGACY_CALCULATION=$(val "${LEGACY_CALCULATION:-false}")
ENABLE_INVOICE_DELETION=$(val "${ENABLE_INVOICE_DELETION:-false}")
DISABLE_READ_ONLY=$(val "${DISABLE_READ_ONLY:-false}")

PASSWORD_RESET_IP_MAX_ATTEMPTS=$(val "${PASSWORD_RESET_IP_MAX_ATTEMPTS:-5}")
PASSWORD_RESET_IP_WINDOW_MINUTES=$(val "${PASSWORD_RESET_IP_WINDOW_MINUTES:-60}")
PASSWORD_RESET_EMAIL_MAX_ATTEMPTS=$(val "${PASSWORD_RESET_EMAIL_MAX_ATTEMPTS:-3}")
PASSWORD_RESET_EMAIL_WINDOW_HOURS=$(val "${PASSWORD_RESET_EMAIL_WINDOW_HOURS:-1}")
PASSWORD_RESET_TOKEN_EXPIRY_MINUTES=$(val "${PASSWORD_RESET_TOKEN_EXPIRY_MINUTES:-15}")

SEC_STRIP_EXIF_FROM_IMAGES=$(val "${SEC_STRIP_EXIF_FROM_IMAGES:-false}")
SUMEX_SETTINGS=$(val "${SUMEX_SETTINGS:-false}")
SUMEX_URL=$(val "${SUMEX_URL:-}")

ENCRYPTION_KEY=$(val "$ENCRYPTION_KEY")
ENCRYPTION_CIPHER=$(val "${ENCRYPTION_CIPHER:-AES-256}")

SETUP_COMPLETED=true
EOF
chmod 600 "$IPCONFIG"

echo "==> waiting for database at $DB_HOSTNAME:$DB_PORT"
i=0
until ephpm php -r '
    mysqli_report(MYSQLI_REPORT_OFF);
    $c = @mysqli_connect($argv[1], $argv[3], $argv[4], $argv[5], (int) $argv[2]);
    exit($c ? 0 : 1);
' "$DB_HOSTNAME" "$DB_PORT" "$DB_USERNAME" "$DB_PASSWORD" "$DB_DATABASE" 2>/dev/null; do
    i=$((i + 1))
    [ "$i" -ge 60 ] && { echo "!!! database at $DB_HOSTNAME:$DB_PORT not reachable after 60 tries" >&2; exit 1; }
    sleep 2
done

# Schema + migrations, then the default admin (skipped once a user exists):
# the same two CLI steps the official image runs.
cd "$HTML"
ephpm php index.php setup/cli/migrate
ephpm php index.php setup/cli/create_default_user

exec ephpm serve --config "$CONFIG" "$@"
