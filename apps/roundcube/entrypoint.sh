#!/bin/sh
# Container entrypoint: the same ROUNDCUBEMAIL_* configuration as the
# official image (config.inc.php + config.docker.inc.php generated from the
# environment, bin/initdb.sh to create/update the schema), then ePHPm.
set -eu

HTML=/var/www/html
STATE=/var/roundcube                   # the volume: config/*.php includes, db/, des key
cd "$HTML"
mkdir -p "$STATE/config" "$STATE/db" /tmp/roundcube-temp logs

# Database: ROUNDCUBEMAIL_DB_TYPE mysql | pgsql | sqlite (default sqlite, as the official image)
: "${ROUNDCUBEMAIL_DB_TYPE:=sqlite}"
case "$ROUNDCUBEMAIL_DB_TYPE" in
    mysql|pgsql)
        [ "$ROUNDCUBEMAIL_DB_TYPE" = mysql ] && defport=3306 || defport=5432
        : "${ROUNDCUBEMAIL_DB_HOST:=db}" "${ROUNDCUBEMAIL_DB_PORT:=$defport}"
        : "${ROUNDCUBEMAIL_DB_USER:=roundcube}" "${ROUNDCUBEMAIL_DB_PASSWORD:=}" "${ROUNDCUBEMAIL_DB_NAME:=roundcubemail}"
        DSNW="${ROUNDCUBEMAIL_DB_TYPE}://${ROUNDCUBEMAIL_DB_USER}:${ROUNDCUBEMAIL_DB_PASSWORD}@${ROUNDCUBEMAIL_DB_HOST}:${ROUNDCUBEMAIL_DB_PORT}/${ROUNDCUBEMAIL_DB_NAME}"
        echo "==> waiting for ${ROUNDCUBEMAIL_DB_TYPE} at ${ROUNDCUBEMAIL_DB_HOST}:${ROUNDCUBEMAIL_DB_PORT}"
        i=0
        until php -r 'exit(@fsockopen($argv[1], (int) $argv[2], $e, $s, 3) ? 0 : 1);' -- "$ROUNDCUBEMAIL_DB_HOST" "$ROUNDCUBEMAIL_DB_PORT" 2>/dev/null; do
            i=$((i + 1)); [ "$i" -ge 60 ] && { echo "!!! database not reachable after 60 tries" >&2; exit 1; }; sleep 2
        done ;;
    sqlite)
        DSNW="sqlite:///${STATE}/db/${ROUNDCUBEMAIL_DB_NAME:-sqlite}.db?mode=0646" ;;
    *) echo "!!! unsupported ROUNDCUBEMAIL_DB_TYPE '$ROUNDCUBEMAIL_DB_TYPE'" >&2; exit 1 ;;
esac

# Mail servers and the rest, same defaults as the official image.
: "${ROUNDCUBEMAIL_DEFAULT_HOST:=localhost}" "${ROUNDCUBEMAIL_DEFAULT_PORT:=143}"
: "${ROUNDCUBEMAIL_SMTP_SERVER:=localhost}" "${ROUNDCUBEMAIL_SMTP_PORT:=587}"
: "${ROUNDCUBEMAIL_PLUGINS:=archive,zipdownload}" "${ROUNDCUBEMAIL_SKIN:=elastic}"
: "${ROUNDCUBEMAIL_USERNAME_DOMAIN:=}" "${ROUNDCUBEMAIL_REQUEST_PATH:=/}"

# The cookie/password encryption key: ROUNDCUBEMAIL_DES_KEY, else one generated
# once and kept in the volume (the official image bakes it into config.inc.php).
if [ -z "${ROUNDCUBEMAIL_DES_KEY:-}" ]; then
    [ -s "$STATE/config/des_key" ] || php -r 'echo bin2hex(random_bytes(12));' > "$STATE/config/des_key"
    ROUNDCUBEMAIL_DES_KEY="$(cat "$STATE/config/des_key")"
fi

plugins_php="$(printf '%s' "$ROUNDCUBEMAIL_PLUGINS" | sed -E "s/[, ]+/', '/g")"
cat > config/config.inc.php <<EOF
<?php
// Generated by entrypoint.sh from the ROUNDCUBEMAIL_* environment at every start.
// Put your own settings in /var/roundcube/config/*.php (the volume); they are included below.
\$config['db_dsnw'] = '${DSNW}';
\$config['imap_host'] = '${ROUNDCUBEMAIL_DEFAULT_HOST}:${ROUNDCUBEMAIL_DEFAULT_PORT}';
\$config['smtp_host'] = '${ROUNDCUBEMAIL_SMTP_SERVER}:${ROUNDCUBEMAIL_SMTP_PORT}';
\$config['username_domain'] = '${ROUNDCUBEMAIL_USERNAME_DOMAIN}';
\$config['des_key'] = getenv('ROUNDCUBEMAIL_DES_KEY') ?: trim((string) @file_get_contents('${STATE}/config/des_key'));
\$config['plugins'] = ['${plugins_php}'];
\$config['skin'] = '${ROUNDCUBEMAIL_SKIN}';
\$config['request_path'] = '${ROUNDCUBEMAIL_REQUEST_PATH}';
\$config['temp_dir'] = '/tmp/roundcube-temp';
\$config['log_driver'] = 'stdout';
\$config['zipdownload_selection'] = true;
// pspell is not available in ePHPm; the spellchecker stays off unless you configure another engine
\$config['enable_spellcheck'] = false;
foreach (glob('${STATE}/config/*.php') ?: [] as \$f) { include \$f; }
EOF
[ -n "${ROUNDCUBEMAIL_DES_KEY}" ] && export ROUNDCUBEMAIL_DES_KEY

# Create or upgrade the database schema.
php bin/initdb.sh --dir="$HTML/SQL" --update \
    || echo "!!! Failed to initialize/update the database. Start with an empty database and restart the container." >&2

exec ephpm serve --config "${EPHPM_CONFIG:-/etc/ephpm/ephpm.toml}" "$@"
