#!/bin/sh
# Container entrypoint: write Tiny File Manager's config.php from the
# environment, then ePHPm in the foreground.
#
# The single-file app reads an optional config.php next to itself that
# overrides its built-in settings (upstream's documented mechanism). It is
# regenerated on every start, so the environment is the source of truth.
set -eu

CONF=/etc/tinyfilemanager/config.php

if [ -z "${TFM_ADMIN_PASSWORD:-}${TFM_ADMIN_PASSWORD_HASH:-}" ]; then
    TFM_ADMIN_PASSWORD="$(ephpm php -r 'echo bin2hex(random_bytes(9));')"
    export TFM_ADMIN_PASSWORD
    echo "==> no TFM_ADMIN_PASSWORD set; generated one for '${TFM_ADMIN_USER:-admin}': $TFM_ADMIN_PASSWORD"
fi

ephpm php -r '
    $e = static fn (string $k, string $d = ""): string => (string) (getenv($k) !== false ? getenv($k) : $d);
    $users = [];
    $admin = $e("TFM_ADMIN_USER", "admin");
    $users[$admin] = $e("TFM_ADMIN_PASSWORD_HASH") ?: password_hash($e("TFM_ADMIN_PASSWORD"), PASSWORD_DEFAULT);
    $readonly = [];
    if ($e("TFM_READONLY_USER") !== "" && ($e("TFM_READONLY_PASSWORD") !== "" || $e("TFM_READONLY_PASSWORD_HASH") !== "")) {
        $users[$e("TFM_READONLY_USER")] = $e("TFM_READONLY_PASSWORD_HASH") ?: password_hash($e("TFM_READONLY_PASSWORD"), PASSWORD_DEFAULT);
        $readonly[] = $e("TFM_READONLY_USER");
    }
    $cfg = [
        "auth_users"                => $users,
        "readonly_users"            => $readonly,
        "root_path"                 => $e("TFM_ROOT_PATH", "/data"),
        "root_url"                  => "",
        "default_timezone"          => $e("TZ", "Etc/UTC"),
        "allowed_upload_extensions" => $e("TFM_ALLOWED_UPLOAD_EXTENSIONS"),
        "online_viewer"             => $e("TFM_ONLINE_VIEWER", "false") === "false" ? false : $e("TFM_ONLINE_VIEWER"),
        "max_upload_size_bytes"     => (int) $e("TFM_MAX_UPLOAD_SIZE_BYTES", "5000000000"),
    ];
    $out = "<?php\n// Generated by entrypoint.sh from the environment on every start.\n";
    foreach ($cfg as $k => $v) {
        $out .= "\$" . $k . " = " . var_export($v, true) . ";\n";
    }
    file_put_contents($argv[1], $out);
' -- "$CONF"
chmod 0640 "$CONF"

exec ephpm serve --config "${EPHPM_CONFIG:-/etc/ephpm/ephpm.toml}" "$@"
