#!/bin/sh
# Container entrypoint: write app/config/parameters.yml from the same
# SYMFONY__ENV__* variables the official wallabag/wallabag image reads, wait
# for the database, install on first start (schema + admin user), warm the
# Symfony cache, then run ePHPm in the foreground.
set -eu

APP=/var/www/wallabag
CONFIG="${EPHPM_CONFIG:-/etc/ephpm/ephpm.toml}"
cd "$APP"

DRIVER="${SYMFONY__ENV__DATABASE_DRIVER:-pdo_sqlite}"
DB_HOST="${SYMFONY__ENV__DATABASE_HOST:-127.0.0.1}"
DB_PORT="${SYMFONY__ENV__DATABASE_PORT:-}"
case "$DB_PORT" in "") case "$DRIVER" in pdo_pgsql) DB_PORT=5432 ;; *) DB_PORT=3306 ;; esac ;; esac

# Values land in YAML double-quoted scalars.
yq() { printf '%s' "$1" | sed 's/\\/\\\\/g; s/"/\\"/g'; }

# A secret must be stable (it signs cookies and tokens). Use SYMFONY__ENV__SECRET
# when set, else generate one once and keep it in the data volume.
if [ -z "${SYMFONY__ENV__SECRET:-}" ]; then
    mkdir -p data
    if [ ! -f data/ephpm-secret ]; then
        ephpm php -r 'echo bin2hex(random_bytes(32));' > data/ephpm-secret
        chmod 600 data/ephpm-secret
    fi
    SYMFONY__ENV__SECRET="$(cat data/ephpm-secret)"
fi

cat > app/config/parameters.yml <<EOF
# Generated by entrypoint.sh on every start from the SYMFONY__ENV__* variables.
parameters:
    database_driver: "$(yq "$DRIVER")"
    database_host: "$(yq "$DB_HOST")"
    database_port: $DB_PORT
    database_name: "$(yq "${SYMFONY__ENV__DATABASE_NAME:-symfony}")"
    database_user: "$(yq "${SYMFONY__ENV__DATABASE_USER:-root}")"
    database_password: "$(yq "${SYMFONY__ENV__DATABASE_PASSWORD:-}")"
    database_path: "%kernel.project_dir%/data/db/wallabag.sqlite"
    database_table_prefix: "$(yq "${SYMFONY__ENV__DATABASE_TABLE_PREFIX:-wallabag_}")"
    database_socket: null
    database_charset: "$(yq "${SYMFONY__ENV__DATABASE_CHARSET:-utf8}")"

    domain_name: "$(yq "${SYMFONY__ENV__DOMAIN_NAME:-http://localhost:8080}")"
    server_name: "$(yq "${SYMFONY__ENV__SERVER_NAME:-Your wallabag instance}")"

    mailer_dsn: "$(yq "${SYMFONY__ENV__MAILER_DSN:-smtp://127.0.0.1}")"

    locale: "$(yq "${SYMFONY__ENV__LOCALE:-en}")"

    secret: "$(yq "$SYMFONY__ENV__SECRET")"

    twofactor_sender: "$(yq "${SYMFONY__ENV__TWOFACTOR_SENDER:-no-reply@wallabag.org}")"

    fosuser_registration: ${SYMFONY__ENV__FOSUSER_REGISTRATION:-false}
    fosuser_confirmation: ${SYMFONY__ENV__FOSUSER_CONFIRMATION:-true}

    fos_oauth_server_access_token_lifetime: 3600
    fos_oauth_server_refresh_token_lifetime: 1209600

    from_email: "$(yq "${SYMFONY__ENV__FROM_EMAIL:-no-reply@wallabag.org}")"

    rss_limit: 50

    rabbitmq_host: "$(yq "${SYMFONY__ENV__RABBITMQ_HOST:-localhost}")"
    rabbitmq_port: ${SYMFONY__ENV__RABBITMQ_PORT:-5672}
    rabbitmq_user: "$(yq "${SYMFONY__ENV__RABBITMQ_USER:-guest}")"
    rabbitmq_password: "$(yq "${SYMFONY__ENV__RABBITMQ_PASSWORD:-guest}")"
    rabbitmq_prefetch_count: ${SYMFONY__ENV__RABBITMQ_PREFETCH_COUNT:-10}

    redis_scheme: "$(yq "${SYMFONY__ENV__REDIS_SCHEME:-tcp}")"
    redis_host: "$(yq "${SYMFONY__ENV__REDIS_HOST:-redis}")"
    redis_port: ${SYMFONY__ENV__REDIS_PORT:-6379}
    redis_path: ${SYMFONY__ENV__REDIS_PATH:-~}
    redis_password: ${SYMFONY__ENV__REDIS_PASSWORD:-~}

    sentry_dsn: ${SYMFONY__ENV__SENTRY_DSN:-~}
EOF

mkdir -p data/db data/assets web/assets/images var/cache var/logs var/sessions

wait_tcp() {
    i=0
    until ephpm php -r 'exit(@fsockopen($argv[1], (int) $argv[2], $e, $s, 2) ? 0 : 1);' "$1" "$2" 2>/dev/null; do
        i=$((i + 1))
        [ "$i" -ge 60 ] && { echo "!!! database at $1:$2 not reachable after 60 tries" >&2; exit 1; }
        sleep 2
    done
}

# Install (schema, migrations, the admin user) when the database is empty.
# `wallabag:install -n` takes the defaults: user wallabag / wallabag /
# wallabag@wallabag.io, exactly as the official image does.
install_if_needed() {
    rm -rf var/cache/prod
    if ! wallabag doctrine:query:sql "SELECT 1 FROM ${SYMFONY__ENV__DATABASE_TABLE_PREFIX:-wallabag_}user" >/dev/null 2>&1; then
        echo "==> installing wallabag (schema + default admin wallabag/wallabag)"
        wallabag wallabag:install --no-interaction
    else
        wallabag doctrine:migrations:migrate --no-interaction
    fi
    wallabag cache:warmup
    echo "==> wallabag is ready"
}

case "$DRIVER:$DB_HOST" in
    pdo_sqlite:*)
        install_if_needed
        ;;
    *:127.0.0.1|*:localhost)
        # The embedded database only exists while `ephpm serve` runs.
        ( wait_tcp "$DB_HOST" "$DB_PORT"; install_if_needed ) &
        ;;
    *)
        echo "==> waiting for database at $DB_HOST:$DB_PORT"
        wait_tcp "$DB_HOST" "$DB_PORT"
        install_if_needed
        ;;
esac

exec ephpm serve --config "$CONFIG" "$@"
